-- Tasks_Field: matches the client-supplied table structure (task_schema.xlsx) exactly,
-- column-for-column, including the client's original naming/typos (AGENT_FM/AGENT_LM).
CREATE TABLE IF NOT EXISTS tasks_field (
    task_id                             BIGINT PRIMARY KEY,
    task_status                         SMALLINT NOT NULL DEFAULT 0, -- 0 Not Started, 1 In Progress, 2 Completed
    job_id                              VARCHAR(23),
    vendor_task_id                      VARCHAR(35),
    prop_id                             BIGINT,
    prop_mgr_id                         BIGINT,
    prop_mgr_fn                         VARCHAR(55),
    prop_mgr_ln                         VARCHAR(55),
    prop_mgr_phone                      VARCHAR(15),
    agent_id                            VARCHAR(12),
    agent_fm                            VARCHAR(55),
    agent_lm                            VARCHAR(55),
    prop_full_addr                      VARCHAR(100),
    prop_st_addr                        VARCHAR(60),
    prop_addr_l1                        VARCHAR(60),
    prop_addr_l2                        VARCHAR(60),
    prop_number                         VARCHAR(10),
    prop_city                           VARCHAR(55),
    prop_pin_cd                         VARCHAR(15),
    prop_district                       VARCHAR(55),
    g_place_id                          VARCHAR(55),
    g_address                           VARCHAR(100),
    g_location                          VARCHAR(55),
    g_latitude                          VARCHAR(25),
    g_longitude                         VARCHAR(25),
    g_loc_type                          VARCHAR(25),
    g_types                             VARCHAR(25),
    g_street_number                     VARCHAR(25),
    g_route                             VARCHAR(25),
    g_route_sh                          VARCHAR(25),
    g_locality                          VARCHAR(25),
    g_sublocality_level_1               VARCHAR(35),
    g_sublocality_level_2               VARCHAR(35),
    g_administrative_area_level_1       VARCHAR(35),
    g_administrative_area_level_2       VARCHAR(35),
    g_administrative_area_level_3       VARCHAR(35),
    g_administrative_area_level_1_sh    VARCHAR(35),
    g_administrative_area_level_2_sh    VARCHAR(35),
    g_administrative_area_level_3_sh    VARCHAR(35),
    g_country                           VARCHAR(35),
    g_country_sh                        VARCHAR(35),
    g_postal_code                       VARCHAR(15),
    g_postal_code_suffix                VARCHAR(15),
    g_bounds                            VARCHAR(35),
    g_viewport                          VARCHAR(35),
    web_url                             VARCHAR(75),
    folder_url                          VARCHAR(75),
    cloud_url                           VARCHAR(75), -- S3 url where photos and videos are stored
    created_by                          VARCHAR(35),
    created_timestamp                   TIMESTAMP,
    updated_by                          VARCHAR(35),
    updated_timestamp                   TIMESTAMP,
    add_info1                           VARCHAR(35),
    add_info2                           VARCHAR(35),
    add_info3                           VARCHAR(35)
);

CREATE INDEX IF NOT EXISTS idx_tasks_field_status ON tasks_field (task_status);
CREATE INDEX IF NOT EXISTS idx_tasks_field_created ON tasks_field (created_timestamp);
CREATE INDEX IF NOT EXISTS idx_tasks_field_updated ON tasks_field (updated_timestamp);
